function yes = IsZero( a )

%--------------------------------------------------------------------------
%   Set = 0 if the matrix is all zeros.
%
%   Since version 1.
%--------------------------------------------------------------------------
%   yes = IsZero( a )
%--------------------------------------------------------------------------
%
%   ------
%   Inputs
%   ------
%   a                         Matrix
%
%   -------
%   Outputs
%   -------
%   yes                       0 if matrix is zero
%
%--------------------------------------------------------------------------

%--------------------------------------------------------------------------
%   Copyright (c) 1993 Princeton Satellite Systems, Inc. 
%   All rights reserved.
%--------------------------------------------------------------------------

[ra,ca]=size(a);
if ( ra==0|ca==0 ),
  yes = 0;
  return;
end

yes = norm(a,1);

